#!/usr/bin/env node
// Containerized Control Plane (infra/control-plane). Docker runs natively or through WSL.
//   node scripts/control-plane.mjs setup        generate infra/control-plane/.env (random secrets; never overwrites)
//   node scripts/control-plane.mjs build        build psacc/control-plane-api and psacc/control-plane-web
//   node scripts/control-plane.mjs up|down|destroy|status|logs [service]
//   node scripts/control-plane.mjs bootstrap    create the first organization and administrator (idempotent)
//   node scripts/control-plane.mjs backup       pg_dump (custom format) → infra/control-plane/backups/<timestamp>.dump + .sha256
//   node scripts/control-plane.mjs restore <f>  stop the API, recreate the database from a backup, migrate, start the API
//   node scripts/control-plane.mjs psql         interactive psql as the schema owner
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { docker, dockerMode } from './lib/docker.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cpDir = join(root, 'infra', 'control-plane');
const envFile = join(cpDir, '.env');
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const hex = (n) => randomBytes(n).toString('hex');
const b64 = (n) => randomBytes(n).toString('base64');
const cmd = process.argv[2] ?? 'status';

function readEnv() {
  const out = {};
  if (!existsSync(envFile)) return out;
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (m) out[m[1]] = m[2];
  }
  return out;
}
const compose = (args, opts = {}) => docker(['compose', ...args], { cwd: cpDir, ...opts });
const requireEnv = () => {
  if (!existsSync(envFile)) {
    console.error('infra/control-plane/.env is missing. Run `pnpm cp:setup` first.');
    process.exit(1);
  }
};
/** Shell inside the Docker host (WSL or native). */
const hostSh = (script, opts = {}) =>
  dockerMode() === 'wsl'
    ? spawnSync('wsl', ['--exec', 'bash', '-c', script], { encoding: 'utf8', stdio: opts.stdio ?? 'inherit' })
    : spawnSync('bash', ['-c', script], { encoding: 'utf8', stdio: opts.stdio ?? 'inherit' });
const daemonPath = (p) => (dockerMode() === 'wsl' ? p.replace(/^([A-Za-z]):\\/, (_, d) => `/mnt/${d.toLowerCase()}/`).replace(/\\/g, '/') : p);

/** Address appliances use to reach this host's published gateway port. */
function hostAddress() {
  // The source address of the default route (not the first address of `hostname -I`, which can be a
  // Docker bridge once other networks exist on the engine).
  const r = hostSh(`ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src") print $(i+1)}'`, { stdio: 'pipe' });
  return (r.stdout ?? '').trim() || '127.0.0.1';
}

let r;
switch (cmd) {
  case 'setup': {
    if (existsSync(envFile)) {
      console.log('infra/control-plane/.env exists — keeping it (delete it to regenerate).');
      break;
    }
    const addr = hostAddress();
    const lines = [
      '# Generated by scripts/control-plane.mjs — workstation stack. Do not commit.',
      `VERSION=${version}`,
      'APP_ENV=development',
      'LOG_LEVEL=info',
      'OPENAPI_ENABLED=false',
      'AUTH_MFA_REQUIRED=false',
      'WEB_PORT=3410',
      'API_PORT=4410',
      'APP_ALLOWED_ORIGINS=http://localhost:3410,http://127.0.0.1:3410',
      'AGENT_GATEWAY_BIND=0.0.0.0',
      'AGENT_GATEWAY_PORT=8643',
      `AGENT_GATEWAY_URL=https://${addr}:8643`,
      'EDGE_HEARTBEAT_SECONDS=15',
      'EDGE_IMAGE_REPOSITORY=psacc/psa-edge',
      `EDGE_IMAGE_VERSION=${version}`,
      'EDGE_IMAGE_DIGEST=',
      `POSTGRES_PASSWORD=${hex(24)}`,
      `PSACC_OWNER_PASSWORD=${hex(24)}`,
      `PSACC_APP_PASSWORD=${hex(24)}`,
      `CSRF_SECRET=${b64(32)}`,
      `DATA_ENCRYPTION_KEY=${b64(32)}`,
      'BOOTSTRAP_ORG_NAME=PSA Control Center',
      'BOOTSTRAP_ORG_SLUG=control-plane',
      'BOOTSTRAP_ADMIN_EMAIL=admin@control-plane.local',
      'BOOTSTRAP_ADMIN_NAME=Platform Administrator',
      `BOOTSTRAP_ADMIN_PASSWORD=Cp-${hex(8)}-${hex(4)}`,
      '',
    ];
    mkdirSync(cpDir, { recursive: true });
    writeFileSync(envFile, lines.join('\n'), { mode: 0o600 });
    console.log(`created infra/control-plane/.env (gateway address https://${addr}:8643). Secrets were not printed.`);
    break;
  }
  case 'build': {
    // The build context is copied without node_modules/.next/dist: a Docker build straight from a
    // Windows mount walks hundreds of thousands of files and never finishes.
    const src = daemonPath(root);
    const stage = `/tmp/psacc-cp-src-${process.pid}`;
    const excludes = ['node_modules', '.next', 'dist', 'out', 'coverage', 'test-results', 'playwright-report', '.git', 'docs', 'infra', 'apps/edge', 'apps/api/test', 'apps/web/e2e', 'apps/web/scripts', 'apps/web/playwright.config.ts'].map((e) => `--exclude='${e}'`).join(' ');
    r = hostSh(`rm -rf ${stage} && mkdir -p ${stage} && tar -C '${src}' ${excludes} --exclude='.env' --exclude='.env.*' -cf - . | tar -C ${stage} -xf -`);
    if (r.status !== 0) break;
    for (const [name, file] of [['api', 'apps/api/Dockerfile'], ['web', 'apps/web/Dockerfile']]) {
      r = docker(['build', '-f', `${stage}/${file}`, '-t', `psacc/control-plane-${name}:${version}`, '--build-arg', `VERSION=${version}`, stage]);
      if (r.status !== 0) break;
      docker(['image', 'inspect', `psacc/control-plane-${name}:${version}`, '--format', `psacc/control-plane-${name}:${version} {{.Id}} {{.Size}} bytes, user {{.Config.User}}`]);
    }
    hostSh(`rm -rf ${stage}`);
    break;
  }
  case 'up':
    requireEnv();
    r = compose(['up', '-d', '--wait']);
    if (r.status === 0) {
      const e = readEnv();
      console.log(`Control Plane: http://localhost:${e.WEB_PORT ?? 3410} (API http://127.0.0.1:${e.API_PORT ?? 4410}/api/v1, agent gateway ${e.AGENT_GATEWAY_URL})`);
    }
    break;
  case 'down':
    requireEnv();
    r = compose(['stop']);
    break;
  case 'destroy':
    requireEnv();
    r = compose(['down', '--volumes', '--remove-orphans']);
    break;
  case 'status':
    requireEnv();
    r = compose(['ps']);
    break;
  case 'logs':
    requireEnv();
    r = compose(['logs', '--tail', '200', ...(process.argv[3] ? [process.argv[3]] : [])]);
    break;
  case 'bootstrap':
    requireEnv();
    r = compose(['run', '--rm', '--no-deps', 'migrate', 'node', 'dist/database/cli.js', 'bootstrap']);
    break;
  case 'backup': {
    requireEnv();
    const dir = join(cpDir, 'backups');
    mkdirSync(dir, { recursive: true });
    const name = `psacc-${new Date().toISOString().replace(/[-:]/g, '').replace(/\.\d+Z$/, 'Z')}.dump`;
    const target = `${daemonPath(dir)}/${name}`;
    r = hostSh(`cd '${daemonPath(cpDir)}' && docker compose exec -T postgres pg_dump -U postgres -Fc psacc > '${target}' && cd '${daemonPath(dir)}' && sha256sum '${name}' > '${name}.sha256' && cat '${name}.sha256'`);
    if (r.status === 0) console.log(`backup written: infra/control-plane/backups/${name}`);
    break;
  }
  case 'restore': {
    requireEnv();
    const file = process.argv[3];
    if (!file || !existsSync(file)) {
      console.error('usage: control-plane.mjs restore <backup.dump>');
      process.exit(2);
    }
    const src = daemonPath(file.includes(':\\') ? file : join(process.cwd(), file));
    // Verify the checksum when one sits next to the file, stop the API, recreate the database, restore, migrate, start.
    r = hostSh(
      `set -e; cd '${dirname(src)}'; if [ -f '${src}.sha256' ]; then sha256sum -c '${src}.sha256'; fi; cd '${daemonPath(cpDir)}'; docker compose stop web api; ` +
        `docker compose exec -T postgres psql -U postgres -v ON_ERROR_STOP=1 -c 'DROP DATABASE IF EXISTS psacc WITH (FORCE)' -c 'CREATE DATABASE psacc OWNER psacc_owner'; ` +
        `docker compose exec -T postgres psql -U postgres -d psacc -v ON_ERROR_STOP=1 -c 'REVOKE ALL ON DATABASE psacc FROM PUBLIC' -c 'GRANT CONNECT, TEMPORARY ON DATABASE psacc TO psacc_app_rw' -c 'ALTER SCHEMA public OWNER TO psacc_owner' -c 'REVOKE ALL ON SCHEMA public FROM PUBLIC' -c 'GRANT USAGE ON SCHEMA public TO psacc_app_rw'; ` +
        `docker compose exec -T postgres pg_restore -U postgres -d psacc --no-owner --role=psacc_owner < '${src}'; ` +
        `docker compose run --rm --no-deps migrate node dist/database/cli.js migrate; docker compose up -d --wait api web`,
    );
    if (r.status === 0) console.log('restore complete');
    break;
  }
  case 'psql':
    requireEnv();
    r = compose(['exec', 'postgres', 'psql', '-U', 'psacc_owner', '-d', 'psacc']);
    break;
  default:
    console.error('usage: node scripts/control-plane.mjs <setup|build|up|down|destroy|status|logs|bootstrap|backup|restore|psql>');
    process.exit(2);
}
process.exit(r?.status ?? 1);
