#!/usr/bin/env node
// Generates local, gitignored environment files with strong random secrets.
// Existing files are never overwritten. Secret values are never printed.
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const hex = (n) => randomBytes(n).toString('hex');
const b64 = (n) => randomBytes(n).toString('base64');

function readEnv(file) {
  const out = {};
  if (!existsSync(file)) return out;
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function writeIfMissing(file, content) {
  if (existsSync(file)) {
    console.log(`  keep     ${file.replace(root, '.')}`);
    return false;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content, { mode: 0o600 });
  console.log(`  created  ${file.replace(root, '.')}`);
  return true;
}

console.log('PSA Control Center — local environment setup');

// 1. Dev PostgreSQL secrets
const infraEnvFile = join(root, 'infra', 'dev', '.env');
writeIfMissing(
  infraEnvFile,
  [
    '# Generated by scripts/dev-setup.mjs — local development only. Do not commit.',
    `POSTGRES_PASSWORD=${hex(24)}`,
    `PSACC_OWNER_PASSWORD=${hex(24)}`,
    `PSACC_APP_PASSWORD=${hex(24)}`,
    '',
  ].join('\n'),
);
const pg = readEnv(infraEnvFile);
const url = (user, pw, db) => `postgres://${user}:${pw}@127.0.0.1:55432/${db}`;

// 2. API environment (development + test + e2e database URLs)
// Seed password: letters + digits, satisfies the 12+ char policy.
const seedPassword = `Dev-${hex(8)}-${hex(4)}`;
writeIfMissing(
  join(root, 'apps', 'api', '.env'),
  [
    '# Generated by scripts/dev-setup.mjs — local development only. Do not commit.',
    'APP_ENV=development',
    'HOST=127.0.0.1',
    'PORT=4210',
    'LOG_LEVEL=info',
    'TRUST_PROXY=loopback',
    'APP_ALLOWED_ORIGINS=http://localhost:3210,http://127.0.0.1:3210',
    'OPENAPI_ENABLED=true',
    'AUTH_MFA_REQUIRED=false',
    'SESSION_IDLE_MINUTES=30',
    'SESSION_ABSOLUTE_HOURS=12',
    `CSRF_SECRET=${b64(32)}`,
    `DATA_ENCRYPTION_KEY=${b64(32)}`,
    '',
    '# Application login (psacc_app: DML only, subject to row-level security)',
    `DATABASE_URL=${url('psacc_app', pg.PSACC_APP_PASSWORD, 'psacc_dev')}`,
    '# Schema owner (migrations only)',
    `MIGRATION_DATABASE_URL=${url('psacc_owner', pg.PSACC_OWNER_PASSWORD, 'psacc_dev')}`,
    '',
    '# Isolated databases for automated tests',
    `TEST_DATABASE_URL=${url('psacc_app', pg.PSACC_APP_PASSWORD, 'psacc_test')}`,
    `TEST_MIGRATION_DATABASE_URL=${url('psacc_owner', pg.PSACC_OWNER_PASSWORD, 'psacc_test')}`,
    `E2E_DATABASE_URL=${url('psacc_app', pg.PSACC_APP_PASSWORD, 'psacc_e2e')}`,
    `E2E_MIGRATION_DATABASE_URL=${url('psacc_owner', pg.PSACC_OWNER_PASSWORD, 'psacc_e2e')}`,
    '',
    '# Password assigned to synthetic seed users (development/test only; refused in staging/production)',
    `SEED_DEFAULT_PASSWORD=${seedPassword}`,
    '',
  ].join('\n'),
);

// 3. Web environment
writeIfMissing(
  join(root, 'apps', 'web', '.env.local'),
  [
    '# Generated by scripts/dev-setup.mjs — local development only. Do not commit.',
    'API_INTERNAL_URL=http://127.0.0.1:4210',
    '',
  ].join('\n'),
);

console.log('\nDone. Secret values were written to the files above and not printed.');
console.log('Seed user password: see SEED_DEFAULT_PASSWORD in apps/api/.env');
